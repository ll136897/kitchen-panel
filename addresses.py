"""地址归一：同一个地方的不同写法要归到一起。

为什么要有这个模块：
    同一个场地在订单里可能有多种写法（"青龙湖"、"青龙湖二期"……），
    但在**筛选、分组、成本场地匹配**时它们应当算同一个地方。

业务口径（用户 2026-09-28 确认）：
    **青龙湖二期 = 青龙湖，算同一个地址。**

这是"业务口径"而不是纯技术规则 —— 以后再冒出新的同类地名，
只改下面的 `CANON_RULES` 一处，订单筛选、成本单价匹配会统统自动跟上，
不用到每个页面里各改一遍（以前踩过"改了 A 忘了 B"的坑）。

规则写法：`(地址里包含这个词 → 归一到这个名字)`
    例：("青龙湖", "青龙湖") → "青龙湖二期"/"青龙湖A区" 都归到 "青龙湖"
"""


# (地址里包含这个词 → 归一到这个名字)
CANON_RULES = (
    ("青龙湖", "青龙湖"),
)


def canonical_address(addr):
    """把地址归一化：'青龙湖二期' → '青龙湖'；没有命中规则就原样返回。"""
    a = (addr or "").strip()
    if not a:
        return a
    for kw, target in CANON_RULES:
        if kw and kw in a:
            return target
    return a


def same_address(a, b):
    """两个地址是不是同一个地方（用于合并、去重判断）"""
    return canonical_address(a) == canonical_address(b)
